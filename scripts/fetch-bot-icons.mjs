// Fetch the site icon of every company whose crawler the live layer shows
// (#56): the AI agents panel puts it beside the bot's name, and each satellite
// carries it at its centre. Each brand's own homepage declares the icon
// (apple-touch-icon or the largest <link rel="icon">, else /favicon.ico).
// The icons are trademarks, shown only to identify the crawler.
//
//   node scripts/fetch-bot-icons.mjs            fetch all, write the manifest
//   node scripts/fetch-bot-icons.mjs --dry-run  report what would be saved, write nothing
//
// Output: public/bot-icons/<brand>.<ext>, and src/data/botIcons.ts with the
// brand -> file map (generated; the app maps bot -> brand in src/data/live.ts).
import fs from 'node:fs/promises';
import path from 'node:path';

const ROOT = path.resolve(import.meta.dirname, '..');
const OUT = path.join(ROOT, 'public', 'bot-icons');
const DRY = process.argv.includes('--dry-run');
// A plain browser UA: several of these sites refuse unknown clients.
const UA = 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130.0 Safari/537.36';

// Brand -> the homepage whose icon stands for its crawlers.
const BRANDS = {
  openai: 'https://openai.com/',
  anthropic: 'https://www.anthropic.com/',
  perplexity: 'https://www.perplexity.ai/',
  google: 'https://www.google.com/',
  apple: 'https://www.apple.com/',
  meta: 'https://www.meta.ai/', // meta.com refuses scripted requests; Meta AI's own site stands for its crawlers
  amazon: 'https://www.amazon.com/',
  bytedance: 'https://www.bytedance.com/',
  mistral: 'https://mistral.ai/',
  cohere: 'https://cohere.com/',
  duckduckgo: 'https://duckduckgo.com/',
  commoncrawl: 'https://commoncrawl.org/',
  diffbot: 'https://www.diffbot.com/',
};

const EXT = { 'image/png': 'png', 'image/svg+xml': 'svg', 'image/x-icon': 'ico', 'image/vnd.microsoft.icon': 'ico', 'image/jpeg': 'jpg', 'image/webp': 'webp' };

async function get(url) {
  const r = await fetch(url, { headers: { 'User-Agent': UA, Accept: '*/*' }, redirect: 'follow', signal: AbortSignal.timeout(15000) });
  if (!r.ok) throw new Error(`HTTP ${r.status} ${url}`);
  return r;
}

/** Icon candidates declared in the page, best first: apple-touch-icon, then the largest icon, SVG counted large. */
function candidates(html, base) {
  const out = [];
  for (const m of html.matchAll(/<link\b[^>]*>/gi)) {
    const tag = m[0];
    const rel = /rel\s*=\s*["']([^"']+)["']/i.exec(tag)?.[1]?.toLowerCase() ?? '';
    const href = /href\s*=\s*["']([^"']+)["']/i.exec(tag)?.[1];
    if (!href || !/(^|\s)(icon|apple-touch-icon|apple-touch-icon-precomposed)(\s|$)/.test(rel)) continue;
    const sizes = /sizes\s*=\s*["']([^"']+)["']/i.exec(tag)?.[1] ?? '';
    const svg = /\.svg(\?|$)/i.test(href) || /image\/svg/i.test(tag);
    const px = svg ? 512 : Math.max(0, ...sizes.split(/\s+/).map((s) => parseInt(s, 10) || 0));
    const score = (rel.includes('apple-touch-icon') ? 1000 : 0) + (px || 32);
    out.push({ url: new URL(href.replace(/&amp;/g, '&'), base).href, score });
  }
  out.sort((a, b) => b.score - a.score);
  out.push({ url: new URL('/favicon.ico', base).href, score: 0 });
  return out;
}

async function iconFor(brand, home) {
  // A homepage that refuses us still leaves /favicon.ico to try.
  let html = '';
  let base = home;
  try {
    const page = await get(home);
    html = await page.text();
    base = page.url;
  } catch (e) {
    console.warn(`  ${brand}: ${e.message}; trying /favicon.ico`);
  }
  for (const c of candidates(html, base)) {
    try {
      const r = await get(c.url);
      const type = (r.headers.get('content-type') ?? '').split(';')[0].trim().toLowerCase();
      const ext = EXT[type] ?? /\.(png|svg|ico|jpg|webp)(\?|$)/i.exec(c.url)?.[1]?.toLowerCase();
      const body = Buffer.from(await r.arrayBuffer());
      if (!ext || body.length < 64) continue; // not an image, or an empty placeholder
      return { file: `${brand}.${ext}`, body, from: c.url };
    } catch (e) {
      console.warn(`  ${brand}: ${e.message}`);
    }
  }
  return null;
}

const manifest = {};
for (const [brand, home] of Object.entries(BRANDS)) {
  try {
    const icon = await iconFor(brand, home);
    if (!icon) {
      console.warn(`- ${brand}: no usable icon`);
      continue;
    }
    manifest[brand] = icon.file;
    console.log(`+ ${brand}: ${icon.file} (${icon.body.length} B) from ${icon.from}`);
    if (!DRY) {
      await fs.mkdir(OUT, { recursive: true });
      await fs.writeFile(path.join(OUT, icon.file), icon.body);
    }
  } catch (e) {
    console.warn(`- ${brand}: ${e.message}`);
  }
}
if (!DRY)
  await fs.writeFile(
    path.join(ROOT, 'src', 'data', 'botIcons.ts'),
    '// Generated by scripts/fetch-bot-icons.mjs: brand -> icon file in public/bot-icons/. Do not edit.\n' +
      `export const BOT_ICON_FILES: Record<string, string> = ${JSON.stringify(manifest, null, 2).replace(/"([a-z]+)":/g, '$1:').replace(/"/g, "'")};\n`,
  );
console.log(`${Object.keys(manifest).length}/${Object.keys(BRANDS).length} icons${DRY ? ' (dry run, nothing written)' : ''}`);
